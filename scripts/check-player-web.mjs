import { chromium, expect } from '@playwright/test';
const browser = await chromium.launch();
try {
  const page = await browser.newPage({ viewport: { width: 1280, height: 1000 } });
  const errors = [];
  page.on('pageerror', error => { errors.push(error.message); console.log('PAGE ERROR', error.message); });
  page.on('console', message => { if (message.type() === 'error') console.log('CONSOLE', message.text()); });
  await page.goto('http://127.0.0.1:3000/player');
  await page.getByRole('button', { name: 'Clásico', exact: true }).click();
  await page.getByRole('combobox', { name: 'Formato', exact: true }).locator('..').click();
  await page.getByRole('option', { name: 'MP4', exact: true }).click();
  const player = page.locator('[data-player-phase]').first();
  await expect(player).toHaveAttribute('data-player-phase', 'content', { timeout: 20000 });
  await player.getByRole('button', { name: 'Reproducir', exact: true }).last().click();
  await expect.poll(() => player.locator('video').first().evaluate(video => video.currentTime)).toBeGreaterThan(0.3);
  await player.getByRole('button', { name: 'Pausar', exact: true }).click();
  await page.screenshot({ path: 'example/app/build/player-first.png' });
  console.log('PASS MP4 plays and pauses');
  const select = async (name, option) => {
    await page.getByRole('combobox', { name, exact: true }).locator('..').click();
    await page.getByRole('option', { name: option, exact: true }).click();
  };
  for (const format of ['HLS', 'DASH', 'CLEARKEY']) {
    await select('Formato', format);
    await expect(player).toHaveAttribute('data-player-source', format.toLowerCase());
    await expect(player).toHaveAttribute('data-player-phase', 'content', { timeout: 20000 });
    await player.getByRole('button', { name: 'Reproducir', exact: true }).last().click({timeout:5000}).catch(async error => { console.log(await page.locator('main').first().innerText()); throw error; });
    await expect.poll(() => player.locator('video').first().evaluate(video => video.currentTime), {timeout:10000}).toBeGreaterThan(0.3);
    await player.getByRole('button', { name: 'Pausar', exact: true }).click();
    console.log('PASS playback', format);
  }
  await player.getByRole('button', {name:'Guardar sin conexión',exact:true}).click();
  await player.getByRole('button', {name:'Descargas',exact:true}).click();
  await expect(player.getByRole('button', {name:'Ver sin conexión',exact:true})).toBeVisible({timeout:20000});
  await page.context().setOffline(true);
  await player.getByRole('button', {name:'Ver sin conexión',exact:true}).click();
  await expect(player).toHaveAttribute('data-player-phase', 'content');
  await expect.poll(() => player.locator('video').first().evaluate(video => video.currentTime)).toBeGreaterThan(0.3);
  await page.context().setOffline(false);
  await player.getByRole('button', {name:/^Eliminar:/}).click();
  await player.getByRole('button', {name:'Descargas',exact:true}).click();
  console.log('PASS encrypted offline media with application-supplied Clear Key (not a persistent license)');
  await select('Formato', 'DASH');
  await expect(player).toHaveAttribute('data-player-phase', 'content');
  await player.getByRole('button', {name:'Ajustes de reproducción',exact:true}).click();
  await select('Calidad', '180p');
  await select('Subtítulos', 'English');
  await player.getByRole('button', {name:'Reproducir',exact:true}).last().click();
  await expect.poll(() => player.locator('video').first().evaluate(video => [...video.textTracks].some(track => track.mode === 'showing'))).toBe(true);
  await player.getByRole('button', {name:'Pausar',exact:true}).click();
  console.log('PASS quality and external text tracks');
  await player.getByRole('button', {name:'Guardar sin conexión',exact:true}).click();
  await player.getByRole('button', {name:'Descargas',exact:true}).click();
  await expect(player.getByRole('button', {name:'Ver sin conexión',exact:true})).toBeVisible({timeout:20000});
  await page.context().setOffline(true);
  await player.getByRole('button', {name:'Ver sin conexión',exact:true}).click();
  await expect(player).toHaveAttribute('data-player-phase', 'content');
  await expect.poll(() => player.locator('video').first().evaluate(video => video.currentTime)).toBeGreaterThan(0.3);
  await page.context().setOffline(false);
  await player.getByRole('button', {name:/^Eliminar:/}).click();
  console.log('PASS offline download, offline playback and removal');
  await select('Formato', 'MP4');
  await page.getByLabel('Vídeo de inicio', {exact:true}).check();
  await expect(player).toHaveAttribute('data-player-phase','splash');
  await player.getByRole('button',{name:'Reproducir',exact:true}).last().click();
  await expect(player).toHaveAttribute('data-player-phase','content',{timeout:15000});
  await expect.poll(() => player.locator('video').first().evaluate(video => video.currentTime)).toBeGreaterThan(0.3);
  await page.getByLabel('Vídeo de inicio', {exact:true}).uncheck();
  console.log('PASS splash before content');
  for (const ads of ['Pre-roll + mid-roll', 'VAST']) {
    await select('Anuncios', ads);
    await expect(player).toHaveAttribute('data-player-phase','content');
    await player.getByRole('button',{name:'Reproducir',exact:true}).last().click();
    await expect(player).toHaveAttribute('data-player-phase','ad',{timeout:10000});
    await expect(player.getByText('Publicidad · Demo',{exact:true})).toBeVisible();
    await expect(player).toHaveAttribute('data-player-phase','content',{timeout:15000});
    console.log('PASS ad break and resume', ads);
  }
  await page.getByRole('button', {name:'Reproducir audio',exact:true}).click();
  const footer = page.locator('.kivora-player-footer');
  await expect(footer).toHaveAttribute('data-player-phase','content');
  await expect.poll(() => footer.locator('video').first().evaluate(video => video.currentTime)).toBeGreaterThan(0.3);
  await footer.getByRole('button',{name:'Ampliar reproductor',exact:true}).click();
  await expect(page.getByRole('dialog')).toBeVisible();
  await page.keyboard.press('Escape');
  await page.getByRole('link',{name:'Ir a componentes',exact:true}).click();
  await expect(footer).toBeVisible();
  await expect(footer.locator('video').first()).toHaveJSProperty('paused',false);
  console.log('PASS audio sheet and persistent playback across navigation');
  expect(errors).toEqual([]);
} finally { await browser.close(); }
